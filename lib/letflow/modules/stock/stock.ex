defmodule Letflow.Modules.Stock do
  @moduledoc """
  REQ-687 / GH #3707 (slice L4 of the stock ledger, decision 0073, assets phase B): module `stock`.
  It registers one ledger, `stock`, with the core ledger (`Letflow.Ledger`), declares the pure posting
  policy `Letflow.Modules.Stock.LedgerPolicy`, renders the stock views (`Letflow.Modules.Stock.Views`)
  and serves three read routes (`Letflow.Modules.Stock.Router`). No tenant gets it installed by
  this change (pilot gate of decision 0073: not enabled for a customer tenant until L6 and L7).

  ## Documents (REQ-712 / GH #3749, assets B4 part 1)

  Version 0.2.0 adds the document foundation on the receipt: the managed record types `stock_receipt`
  (header) and `stock_receipt_line`, shipped by `priv/modules/stock/pack.json` (generated by
  `priv/modules/stock/generate_pack.exs`), the versioned document type `stock_receipt` (registered by
  `on_install/3`; numbering per calendar year, prefix `RCP`, pad 6, no legal entity), and six document
  routes (`Letflow.Modules.Stock.Router`, context `Letflow.Modules.Stock.Documents`). A document is
  a draft (editable, discardable) or issued (fixed); number, state and issued time are read from the
  versioned document, not stored on the header. Master checks (linked location, active employee,
  counterparty, unit and lot of each line) and the event-time window run at issue only. Nothing posts
  to the ledger yet (REQ-713). Assumptions, owner may change at GATE B: numbering, no legal entity,
  100 lines at most, the responsible employee is not bound to the org unit.

  ## Slots and their order (append-only, rule 12)

  `sku, location, org_unit, responsible, lot`, all uuid text. `sku` is slot 1 because the sign rule
  `zero_sum_by_slot_1` sums per distinct slot-1 value, so a two-leg cause conserves the quantity per
  sku, and the key indexes serve sku and location reads; `org_unit` is the scope slot (decision 0076
  R7). `responsible` and `lot` may be empty. The unit of measure is the leg's `unit_ref`, not a slot.

  ## Causes

  `receipt` (positive), `issue` and `write_off` (negative; write_off needs a reason), `transfer`,
  `hand_over` and `return` (zero sum per sku). Assumption, owner may change at GATE B: the six
  causes, the 96-hour lateness, the slot order.

  ## Permissions

  `StockPost`, `StockReverse`, `StockRead`, `StockReconcile`; no role grants, so only TENANT_ADMIN and
  PLATFORM_ADMIN hold them (OQ-11 of decision 0073 stays open for the owner).
  """

  @behaviour Letflow.Modules.Module

  import Letflow.Modules.Module, only: [defmanifest: 1]

  alias Letflow.Documents
  alias Letflow.Modules.EntityActivation

  # Must stay equal to `manages_entity_types` in the manifest below (defmanifest takes literals).
  @types ["stock_receipt", "stock_receipt_line"]

  # Same shape as the procurement registration; assumptions, owner may change at GATE B.
  @receipt_type %{
    key: "stock_receipt",
    owner_module: "stock",
    numbering_scope: :year,
    number_prefix: "RCP",
    number_pad: 6,
    legal_entity_required: false,
    declared_fields: %{}
  }

  @impl true
  defmanifest(
    id: "stock",
    version: "0.2.0",
    depends_on: ["catalog_items", "locations", "org"],
    pack: "modules/stock/pack.json",
    permissions: [:StockPost, :StockReverse, :StockRead, :StockReconcile],
    role_grants: %{},
    required_roles: [],
    settings_schema: nil,
    route_policies: [
      {"GET", "/balances", :StockRead},
      {"GET", "/movements", :StockRead},
      {"GET", "/reconcile", :StockReconcile},
      {"POST", "/documents", :StockPost},
      {"PUT", "/documents/:id", :StockPost},
      {"DELETE", "/documents/:id", :StockPost},
      {"POST", "/documents/:id/issue", :StockPost},
      {"GET", "/documents", :StockRead},
      {"GET", "/documents/:id", :StockRead}
    ],
    manages_entity_types: ["stock_receipt", "stock_receipt_line"],
    scope_declarations: %{
      "stock_receipt" => {:column, "org_unit_id"},
      "stock_receipt_line" => {:column, "org_unit_id"}
    },
    ledger: %{
      "stock" => %{
        ledger_ids: {:fixed, ["stock"]},
        slots: [
          %{name: "sku", format: :uuid, required: true},
          %{name: "location", format: :uuid, required: true},
          %{name: "org_unit", format: :uuid, required: true},
          %{name: "responsible", format: :uuid, required: false},
          %{name: "lot", format: :uuid, required: false}
        ],
        causes: %{
          "receipt" => %{sign_rule: :positive, reason_required: false},
          "issue" => %{sign_rule: :negative, reason_required: false},
          "write_off" => %{sign_rule: :negative, reason_required: true},
          "transfer" => %{sign_rule: :zero_sum_by_slot_1, reason_required: false},
          "hand_over" => %{sign_rule: :zero_sum_by_slot_1, reason_required: false},
          "return" => %{sign_rule: :zero_sum_by_slot_1, reason_required: false}
        },
        key_bounds: [],
        permissions: %{
          post: :StockPost,
          reverse: :StockReverse,
          read: :StockRead,
          reconcile: :StockReconcile
        },
        scope_slot: "org_unit",
        max_event_lateness_hours: 96,
        error_aliases: %{"insufficient_balance" => "insufficient_stock"},
        policy: {Letflow.Modules.Stock.LedgerPolicy, :declare}
      }
    }
  )

  @impl true
  def router, do: Letflow.Modules.Stock.Router

  @impl true
  def on_install(prefix, _settings, ctx) do
    with :ok <- EntityActivation.activate_and_promote(prefix, ctx, @types),
         {:ok, _type} <- Documents.register_type(prefix, @receipt_type, ctx) do
      :ok
    end
  end
end
