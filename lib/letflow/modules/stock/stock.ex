defmodule Letflow.Modules.Stock do
  @moduledoc """
  REQ-687 / GH #3707 (slice L4 of the stock ledger, decision 0073, assets phase B): module `stock`.
  It registers one ledger, `stock`, with the core ledger (`Letflow.Ledger`), declares the pure posting
  policy `Letflow.Modules.Stock.LedgerPolicy`, renders the stock views (`Letflow.Modules.Stock.Views`)
  and serves three read routes (`Letflow.Modules.Stock.Router`). The ledger part has no table of its own
  (those are REQ-679 and slice L7); no tenant gets it installed by this change (pilot gate of decision
  0073: not enabled for a customer tenant until L6 and L7).

  REQ-700 / GH #3737 (version 0.2.0, assets phase B counts): the count order. Three module-managed
  record types shipped by the pack `priv/modules/stock/pack.json` (`count_order`, `count_order_scope`,
  `count_commission_member`, generated by `priv/modules/stock/generate_pack.exs`), all scoped by the
  column `org_unit_id` (decision 0076 R7), the four count document types registered by `on_install/3`
  and seven routes (`Letflow.Modules.Stock.Counts`, `Letflow.Modules.Stock.Router`). No ledger call.
  `depends_on` is `["org", "locations"]` (the count functions read both; the boundary lint
  requires it), so a tenant installs org and locations before stock.

  ## Slots and their order (append-only, rule 12)

  `sku, location, org_unit, responsible, lot`, all uuid text. `sku` is slot 1 because the sign rule
  `zero_sum_by_slot_1` sums per distinct slot-1 value, so a two-leg cause conserves the quantity per
  sku, and the key indexes serve sku and location reads; `org_unit` is the scope slot (decision 0076
  R7). `responsible` and `lot` may be empty. The unit of measure is the leg's `unit_ref`, not a slot.

  ## Causes

  `receipt` (positive), `issue` and `write_off` (negative; write_off needs a reason), `transfer`,
  `hand_over` and `return` (zero sum per sku). Assumption, owner may change at GATE B: the six
  causes, the 96-hour lateness, the slot order.

  ## Permissions

  `StockPost`, `StockReverse`, `StockRead`, `StockReconcile`, `StockCountOrder` (REQ-700; the count
  record permission `StockCountRecord` comes with REQ-701, the first route that uses it); no role grants, so only TENANT_ADMIN and
  PLATFORM_ADMIN hold them (OQ-11 of decision 0073 stays open for the owner).
  """

  @behaviour Letflow.Modules.Module

  import Letflow.Modules.Module, only: [defmanifest: 1]

  alias Letflow.Documents
  alias Letflow.Modules.EntityActivation

  # Must stay equal to `manages_entity_types` in the manifest below (defmanifest takes literals);
  # `count_order` first, the two children carry a foreign key onto it.
  @types ["count_order", "count_order_scope", "count_commission_member"]

  # The four count document types (decision 0079 section 9); numbering restarts each year.
  @document_types for {key, prefix} <- [
                        {"count.order", "CO"},
                        {"count.sheet", "CS"},
                        {"count.differences", "CD"},
                        {"count.posting", "CP"}
                      ],
                      do: %{
                        key: key,
                        owner_module: "stock",
                        numbering_scope: :year,
                        number_prefix: prefix,
                        number_pad: 4,
                        legal_entity_required: false,
                        declared_fields: %{}
                      }

  @impl true
  defmanifest(
    id: "stock",
    version: "0.2.0",
    depends_on: ["org", "locations"],
    pack: "modules/stock/pack.json",
    permissions: [:StockPost, :StockReverse, :StockRead, :StockReconcile, :StockCountOrder],
    role_grants: %{},
    required_roles: [],
    settings_schema: nil,
    route_policies: [
      {"GET", "/balances", :StockRead},
      {"GET", "/movements", :StockRead},
      {"GET", "/reconcile", :StockReconcile},
      {"POST", "/counts", :StockCountOrder},
      {"PUT", "/counts/:id", :StockCountOrder},
      {"POST", "/counts/:id/issue", :StockCountOrder},
      {"POST", "/counts/:id/cancel", :StockCountOrder},
      {"GET", "/counts", :StockRead},
      {"GET", "/counts/:id", :StockRead},
      {"GET", "/counts/:id/document", :StockRead}
    ],
    manages_entity_types: ["count_order", "count_order_scope", "count_commission_member"],
    scope_declarations: %{
      "count_order" => {:column, "org_unit_id"},
      "count_order_scope" => {:column, "org_unit_id"},
      "count_commission_member" => {:column, "org_unit_id"}
    },
    ledger: %{
      "stock" => %{
        ledger_ids: {:fixed, ["stock"]},
        slots: [
          %{name: "sku", format: :uuid, required: true},
          %{name: "location", format: :uuid, required: true},
          %{name: "org_unit", format: :uuid, required: true},
          %{name: "responsible", format: :uuid, required: false},
          %{name: "lot", format: :uuid, required: false}
        ],
        causes: %{
          "receipt" => %{sign_rule: :positive, reason_required: false},
          "issue" => %{sign_rule: :negative, reason_required: false},
          "write_off" => %{sign_rule: :negative, reason_required: true},
          "transfer" => %{sign_rule: :zero_sum_by_slot_1, reason_required: false},
          "hand_over" => %{sign_rule: :zero_sum_by_slot_1, reason_required: false},
          "return" => %{sign_rule: :zero_sum_by_slot_1, reason_required: false}
        },
        key_bounds: [],
        permissions: %{
          post: :StockPost,
          reverse: :StockReverse,
          read: :StockRead,
          reconcile: :StockReconcile
        },
        scope_slot: "org_unit",
        max_event_lateness_hours: 96,
        error_aliases: %{"insufficient_balance" => "insufficient_stock"},
        policy: {Letflow.Modules.Stock.LedgerPolicy, :declare}
      }
    }
  )

  @impl true
  def router, do: Letflow.Modules.Stock.Router

  @impl true
  def on_install(prefix, _settings, ctx) do
    with :ok <- EntityActivation.activate_and_promote(prefix, ctx, @types) do
      Enum.reduce_while(@document_types, :ok, fn attrs, :ok ->
        case Documents.register_type(prefix, attrs, ctx) do
          {:ok, _type} -> {:cont, :ok}
          {:error, reason} -> {:halt, {:error, reason}}
        end
      end)
    end
  end
end
