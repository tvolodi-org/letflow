defmodule Letflow.Modules.Stock do
  @moduledoc """
  REQ-687 / GH #3707 (slice L4 of the stock ledger, decision 0073, assets phase B): module `stock`.
  It registers one ledger, `stock`, with the core ledger (`Letflow.Ledger`), declares the pure posting
  policy `Letflow.Modules.Stock.LedgerPolicy`, renders the stock views (`Letflow.Modules.Stock.Views`)
  and serves three read routes (`Letflow.Modules.Stock.Router`). No tenant gets it installed by
  this change (pilot gate of decision 0073: not enabled for a customer tenant until L6 and L7).

  ## Documents (REQ-712 / GH #3749, assets B4 part 1)

  Version 0.2.0 adds the document foundation on the receipt: the managed record types `stock_receipt`
  (header) and `stock_receipt_line`, shipped by `priv/modules/stock/pack.json` (generated by
  `priv/modules/stock/generate_pack.exs`), the versioned document type `stock_receipt` (registered by
  `on_install/3`; numbering per calendar year, prefix `RCP`, pad 6, no legal entity), and six document
  routes (`Letflow.Modules.Stock.Router`, context `Letflow.Modules.Stock.Documents`). A document is
  a draft (editable, discardable) or issued (fixed); number, state and issued time are read from the
  versioned document, not stored on the header. Master checks (linked location, active employee,
  counterparty, unit and lot of each line) and the event-time window run at issue only.
  Assumptions, owner may change at GATE B: numbering, no legal entity, 1000 lines at most, the
  responsible employee is not bound to the org unit.

  ## Posting and reversal (REQ-713 / GH #3748, assets B4 part 2)

  Version 0.3.0 adds the bookkeeping type `stock_posting_mark`, the write handlers `post_document`
  and `reverse_document` (`Letflow.Modules.Stock.Handlers`, both `posts_ledger: "stock"`), the
  process definitions `stock_receipt` and `stock_reversal` (one HUMAN_TASK each, shipped in the pack
  and stamped at install) and the routes `post`, `reverse` and `cancel`. The issue step starts one
  `stock_receipt` instance; completing its task posts the receipt and writes a `posted` mark in one
  transaction. Install leaves the definitions as stamped drafts; the issue and reverse routes
  activate them lazily with the request's own activator (`Letflow.Modules.Stock.Documents.Posting`).
  A unique constraint on (`document_id`, `mark`) of the mark type allows one posted and one reversed
  mark per document, so a second completion is refused and nothing is written.

  ## Transfer, hand over and return (REQ-721 / GH #3770, assets phase B P37; version 0.5.0)

  Three more document kinds with two sides per line, built on the same code as the receipt through
  the kind table `Letflow.Modules.Stock.Documents.Kinds`: the managed types `stock_transfer`,
  `stock_handover`, `stock_return` (each with a `_line` type, all scoped by the column `org_unit_id`),
  the document types `TRF`, `HOV`, `RET` (year numbering, pad 6) and the process definitions of the
  same names. Posting writes one ledger entry with two legs per line (`-q` at the from side, `+q` at
  the to side). No new route, permission or ledger rule.

  ## Issue and write off (REQ-715 / GH #3746; version 0.6.0)

  Two more document kinds on the same routes, `issue` and `write_off` (`Documents.Kinds` is the kind
  table): the managed types `stock_issue`, `stock_issue_line`, `stock_writeoff`, `stock_writeoff_line`
  (all scoped by `org_unit_id`), the document types `stock_issue` (ISS) and `stock_writeoff` (WOF),
  numbered per year, and the process definitions `stock_issue` and `stock_writeoff`. They post with the
  same `post_document` handler; the legs are negative and the ledger refuses a posting below zero
  (`insufficient_stock`). A line has no price or value. A write-off carries `reason_code` (`lost`,
  `damaged`, `used_up`, `other`) and an optional `reason_text`. An existing installation gets the new
  types and definitions by reinstalling the module; there is no upgrade hook. No route, permission or
  migration. Assumptions, owner may change at GATE B: the prefixes, the reason list, no counterparty.

  ## Counts (REQ-700 / GH #3737, assets phase B counts; version 0.3.0)

  The count order: three module-managed record types (`count_order`, `count_order_scope`,
  `count_commission_member`), all scoped by the column `org_unit_id` (decision 0076 R7), the four
  count document types registered by `on_install/3` and seven routes
  (`Letflow.Modules.Stock.Counts`, `Letflow.Modules.Stock.Router`). No ledger call. `depends_on`
  gains `org` and `locations` (the count functions read both; the boundary lint requires it).

  ## Receipt fields (REQ-714 / GH #3747; version 0.4.0)

  The receipt types gain optional `supplier_document_ref` and `received_on` (header) and `unit_price`
  and `line_value` (line). Price and value live on the document only: the posting code reads literal
  keys and never copies them to the ledger. At issue the lot is checked against the item's tracking
  policy and `received_on` may not be after the event day in Asia/Almaty (`Documents.Checks`).
  No route, permission or migration. Assumptions, owner may change at GATE B: the constant zone, the
  date check at issue, serial-tracked goods refused.

  ## Count sheet (REQ-701 / GH #3736; version 0.5.0)

  Two more module-managed record types, `count_sheet_line` and `count_entry` (both scoped by the column
  `org_unit_id`), a field `sheet_document_id` on `count_order`, the permission `StockCountRecord` and
  seven routes (`Letflow.Modules.Stock.CountSheet`, delegated from `Counts`): open the count at the
  cut-off (book quantities from the stock ledger through `Ledger.authorize/3` and `Ledger.balances/4`
  only), typed input, surplus lines, the append-only entry log, close (issues the `count.sheet`
  document). The stock module is installed on no tenant yet, so the changed pack touches no existing row.

  ## Signing and the differences sheet (REQ-717 / GH #3764; version 0.6.0)

  One more module-managed record type, `count_signature` (append-only, scoped by the column
  `org_unit_id`), five optional fields on `count_order` and five routes
  (`Letflow.Modules.Stock.CountDifferences`, delegated from `Counts`): the chair records the signers
  of the count sheet, the differences sheet is issued from the issued sheet content, the chair records
  its signers and the count becomes `signed`. No ledger call (the posting is REQ-718). Existing tenants
  with `stock` installed take the new type through the module-upgrade path; the new header fields are
  optional, so a `counted` count that exists already simply has none of them.
  Assumption, owner may change at GATE B: "signed" is a paper signature recorded by the chair.

  ## Count paperwork (REQ-719 / GH #3762; version 0.7.0)

  One read route, `GET /counts/:id/paperwork/:kind` (`StockRead`), answers the `.xlsx` of an issued count
  order, count sheet or differences sheet with signer lines (`Letflow.Modules.Stock.CountPaperwork`,
  `CountPaperworkSource`). No migration, record type or permission.

  ## Count worksheet (T-1905; no version bump)

  `GET /counts/:id/print/worksheet` (PDF) and `GET /counts/:id/paperwork/worksheet` (xlsx), `?lang`, `?expected=0|1`
  (`StockRead`, the two existing routes with one more `kind`): a print of an `ordered` or `counting` order for the
  field, with empty boxes for the counted quantity (`CountWorksheet`, `CountPaperworkSource.read_worksheet/4`).
  Not a document of record: no number, no posting, no write. No migration, record type or permission.

  ## Official forms Z-3 and Z-5 (T-1417, phase E5c; no version bump)

  `GET /documents/:id/print?form=z5` prints the issued transfer on Z-5 / Q-5 (annex 29), and the new read
  route `GET /stock-card/print?sku&location[&lot]&format&lang` (`StockRead`, the guard of `/movements`) prints
  the stock card of one item at one place on Z-3 / Q-3 (annex 27), both on the E5b print engine
  (`FormZ5`, `FormZ3`, `StockCardSource`). No migration, record type or permission.

  ## Official form Z-1 (T-1912; no version bump)

  `GET /documents/:id/print?form=z1&format=pdf|docx&lang=ru|kk` prints the issued or posted receipt on Z-1 / Қ-1
  (annex 25), the receipt order. The mapper `FormZ1` and layout `priv/print_forms/z1.json` follow Z-2; the web
  offers the menu on receipts in issued and posted state. Blank cells for every gap; nothing is invented
  (mapping doc `docs/assets/kz-forms-mapping.md` section 7.1).

  ## Official form Z-6 (T-1914; no version bump)

  `GET /documents/:id/print?form=z6&format=pdf|docx&lang=ru|kk` prints the issued or posted write-off on Z-6 / Қ-6
  (annex 30), the act of writing off stock. The mapper `FormZ6` and layout `priv/print_forms/z6.json` follow Z-1;
  the commission block, approver, price and sum and the "in words" lines print blank (REQ-776 is not built; mapping
  doc section 7.2). The web offers the menu on write-offs in issued, posted and reversed state.

  ## Document print (REQ-737 / GH #3860; version 0.13.0)

  One more read route, `GET /documents/:id/print?lang=ru|kk|en` (`StockRead`, the guard of `GET /documents/:id`):
  the printed act of an issued transfer, hand over or return as an A4 PDF with two signer rows
  (`Letflow.Modules.Stock.DocumentPrint`, `DocumentPrintSource`), rendered from the issued version content.
  No migration, record type or permission.

  ## Change of kind, stock leg (REQ-760 / GH #3901; version 0.16.0)

  The cause `kind_change_out` (negative, one leg per line at `from`) and the write handler
  `post_kind_change_out` post the stock side of an assets change of kind (process definition
  `assets_kind_change` of module `assets`). `post_document` refuses that cause. A module installed at an
  earlier version has no upgrade hook for it (reinstall; QA only).

  ## Count print (REQ-736 / GH #3861; version 0.12.0)

  One more read route, `GET /counts/:id/print/:kind?lang=ru|kk|en` (`StockRead`): the same three issued
  documents as an A4 PDF with signer lines (`Letflow.Modules.Stock.CountPrint`, rendered by
  `Letflow.Documents.PrintLayout`). It shares `CountPaperworkSource.read/4` with the xlsx route. No
  migration, record type or permission.

  ## Count scan (REQ-716 / GH #3765; version 0.8.0)

  One more route, `POST /counts/:id/scan` (permission `StockCountRecord`, `CountSheet.scan/4`): a
  keyboard-scanner code is resolved with `Letflow.Modules.Codes.resolve/2`; an item or lot code adds one
  unit to its single line, a `count_entry` with `method: scan` is appended, and a `scan_id` is counted
  once. `count_entry` gains the optional fields `scan_id`, `code_id`, `scanned_text`, `location_id`. No
  migration, no new permission; `depends_on` gains `codes` (the scan reads `Codes.resolve/2`; the boundary
  lint requires it); the stock module is installed on no tenant yet. Assumptions, owner may
  change at GATE B: see the `CountSheet` scanner section.

  ## Opening balances (REQ-725 / GH #3775 and REQ-726 / GH #3774; version 0.9.0)

  The managed types `stock_opening` (header) and `stock_opening_line` (per-line location, responsible and
  real receipt date; no event time), the versioned document type `stock_opening` (prefix `OPN`, per
  year, pad 6), the route `POST /documents/:id/check` (all line checks, nothing written), the cause
  `opening` (positive) and the process definition `stock_opening` (a `submit` task and an `approve`
  task kept apart by `distinct_from`; completing `approve` posts). The entry's event time is its
  posting time. Assumptions, owner may change at GATE B: 1000 lines, `OPN` per year, the second person.

  ## Voice draft routes (REQ-741 / GH #3879; version 0.14.0)

  Two read-only routes, `POST /voice/draft` (audio) and `POST /voice/draft-text` (typed), served by
  `Letflow.Modules.Stock.VoiceService` under the existing `StockPost` permission. They turn a phrase
  into a server-checked draft from the caller's own active items and locations; nothing is stored. No
  migration, no new permission.

  ## Posting a count (REQ-718 / GH #3763; version 0.11.0)

  The cause `count_difference` (sign rule `any`, a reason required), the write handler `post_count`
  (`posts_ledger: "stock"`), the process definition `stock_count_posting` (one HUMAN_TASK `post`) and
  four routes over `Letflow.Modules.Stock.CountPosting`: `POST /counts/:id/post`, `POST
  /counts/:id/reverse`, `POST /counts/:id/posting-record` and `GET /counts/:id/posting-document`. One
  ledger entry per signed differences sheet, one leg per difference line, posted as a DELTA (counted
  minus book at the cut-off). Reversal reuses `stock_reversal` and `reverse_document`. No migration,
  no new permission. Assumption, owner may change at GATE B (D-086): the count freeze (decision 0079
  section 4, split plan row C7) is not built by REQ-718 (REQ-765 adds it as an optional mode); in the
  default mode postings during counting are not blocked. The module is
  installed on no tenant yet; the new pack definition and the new `count_order` fields reach an
  existing install through the module-upgrade path.

  ## Count freeze (REQ-765 / GH #3906; version 0.17.0)

  The second count mode, freeze locations (owner decision D-094; `Letflow.Modules.Stock.FreezeState`,
  `Letflow.Modules.Stock.FreezeGuard`): `count_order` gains the flag `freeze_locations` and the freeze
  fields, `open/3` of such an order stores one `count_freeze_location` row per frozen location (the roots
  and everything below them), and the posting guard of the stock registration refuses every other stock
  posting on a frozen (org unit, location) pair with `location_frozen`, naming the count. The time limit
  is the module setting `count_freeze_limit_minutes` (default 120). One read route, `GET
  /frozen-locations` (`StockRead`). No migration, no new permission. The no-freeze count of REQ-718 is
  unchanged. Assumptions, owner may change at GATE B: the pair rule, the refused task stays pending.

  ## Opening line import (REQ-727 / GH #3773; version 0.10.0)

  The manifest registers `import_opening_line/3` for `stock_opening_line` (`:import_functions`): an xlsx
  file of lines goes through the record import route (`?upsert_by=external_ref`) into a DRAFT opening
  document named by the header's external id; it never posts and does not run the line checks (the
  check route does). See `Letflow.Modules.Stock.Documents.OpeningImport`. No route, permission or
  migration. Assumptions, owner may change at GATE B: reference cells use the row's external-ref system.

  ## Slots and their order (append-only, rule 12)

  `sku, location, org_unit, responsible, lot`, all uuid text. `sku` is slot 1 because the sign rule
  `zero_sum_by_slot_1` sums per distinct slot-1 value, so a two-leg cause conserves the quantity per
  sku, and the key indexes serve sku and location reads; `org_unit` is the scope slot (decision 0076
  R7). `responsible` and `lot` may be empty. The unit of measure is the leg's `unit_ref`, not a slot.

  ## Causes

  `receipt` and `opening` (positive), `issue` and `write_off` (negative; write_off needs a reason), `transfer`,
  `hand_over` and `return` (zero sum per sku), `count_difference` (REQ-718, sign rule `any`, a reason
  required). Assumption, owner may change at GATE B: the seven causes, the 96-hour lateness, the slot order.

  ## Permissions

  `StockPost`, `StockReverse`, `StockRead`, `StockReconcile`, `StockCountOrder` (REQ-700) and
  `StockCountRecord` (REQ-701: open, count, add surplus lines, close). TENANT_ADMIN, PLATFORM_ADMIN and
  STOREKEEPER (D-093, decision 0081) hold them; STOREKEEPER holds all but `StockReconcile` (an administrative
  reconciliation view; one line in `role_grants` if the owner wants it). OQ-11 of decision 0073 stays open.
