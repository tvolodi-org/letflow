defmodule Letflow.Notifications.Files do
  @moduledoc """
  The tenant-scoped NOTIFICATION FILE AREA (T-2596, pilot gap G12): the place
  the "file" channel of a notification step writes into.

  ## What the area is

  A table in the tenant's own schema (`notification_files`) that holds the
  BYTES of the rendered notification, the template it came from, the name the
  server generated for it and the instance that produced it.

  It is a DATABASE area, not a directory. The pilot's spike (section 2.h) found
  that no tenant-scoped area for generated files exists today -- the attachment
  service keeps photos only (every upload goes through an image check and a
  virus scan) and the data export streams a download without storing anything.
  A notification file is neither: the platform renders it, so the bytes never
  come from a tenant's upload.

  ## Why "never an arbitrary server path" holds by construction

  Three layers, and none of them is a check that could be forgotten:

    1. there is NO file-system path at all -- the bytes are a column of a row
       in the tenant's schema, so there is nothing to escape;
    2. the NAME of the row is generated by the SERVER (`stored_name/1`: a
       sanitised stem plus a fresh uuid). The name a definition declares is
       never used verbatim, so even a name that slipped past the activation
       fence (`Letflow.Definitions.NotifyCalls` refuses a path-like name with a
       fixed code) cannot become a path;
    3. the declared name is checked at ACTIVATION, so the refusal happens
       before the version is switched on, not when the step runs.

  ## The tenant

  The tenant of a row is DERIVED from the prefix it is written into, never
  taken from the caller (decision 0003's addendum, INV-1 (c)). A prefix that
  names no tenant is a refusal: nothing is written.

  ## The retention

  Every file carries an `expires_at`: `retain_days/0` days after it was
  written. `delete_expired/1` removes the files whose moment has passed. The
  sweep that CALLS it is not part of this change (the tenant's scheduled jobs
  are the place for it); the rule and the function are here, with their tests.

  ## Never raises

  Every failure is an error tuple: a prefix that names no tenant, a file that
  is too large, a row that cannot be written.
  """

  import Ecto.Query

  alias Letflow.Notifications.File
  alias Letflow.Repo
  alias Letflow.TenantProvisioning

  # The cap of ONE rendered file. The renderer bounds the template text and
  # every value it substitutes, so the file is bounded already; this is the
  # safety bound of the AREA, and it is checked BEFORE the bytes are stored
  # (SF-01: the byte bound comes first).
  @max_file_bytes 1_048_576

  # The cap of the declared name and of the sanitised stem of the stored name.
  @max_declared_name_bytes 255
  @stem_max_bytes 40

  # How long a file is kept. A SETTING of the area, not a rule of the process:
  # the value is a constant here and a tenant setting later.
  @retain_days 30

  @content_type "text/plain; charset=utf-8"

  @doc """
  Writes one file into the area of the tenant of `prefix`.

  `attrs` carries:

    * `:declared_name` -- the name the definition declared (already refused at
      activation if it was path-like). It is NOT stored verbatim: the server
      generates the name of the row;
    * `:template_key` -- the registered template the bytes were rendered from;
    * `:bytes` -- the rendered bytes;
    * `:trigger_ref` -- the instance that produced the file (the same reference
      the delivery log carries).

  The tenant of the row is derived from `prefix`. Returns `{:ok, row}` or
  `{:error, code}`; the codes are `:invalid_schema_name` (the prefix names no
  tenant), `:file_too_large` (the bytes are over the cap) and
  `:file_write_failed` (the row could not be written).
  """
  @spec write(String.t(), map()) :: {:ok, File.t()} | {:error, atom()}
  def write(prefix, attrs) when is_binary(prefix) and is_map(attrs) do
    with {:ok, tenant_id} <- TenantProvisioning.tenant_id_for_schema_name(prefix),
         {:ok, bytes} <- bytes(attrs),
         :ok <- size(bytes) do
      now = DateTime.utc_now() |> DateTime.truncate(:microsecond)

      attrs = %{
        tenant_id: tenant_id,
        name: stored_name(Map.get(attrs, :declared_name)),
        template_key: Map.get(attrs, :template_key),
        content_type: Map.get(attrs, :content_type) || @content_type,
        byte_size: byte_size(bytes),
        sha256: sha256(bytes),
        bytes: bytes,
        trigger_ref: Map.get(attrs, :trigger_ref),
        inserted_at: now,
        expires_at: DateTime.add(now, @retain_days * 24 * 60 * 60, :second)
      }

      case Repo.insert(File.changeset(attrs), prefix: prefix) do
        {:ok, row} -> {:ok, row}
        {:error, _changeset} -> {:error, :file_write_failed}
      end
    end
  end

  def write(_prefix, _attrs), do: {:error, :file_write_failed}

  @doc """
  The tenant's files, newest first, at most 100 rows. The BYTES are never
  selected here (the list is a list of names, not of payloads). The tenant is
  the `:prefix` only (INV-1).
  """
  @spec list(String.t()) :: {:ok, [map()]}
  def list(prefix) when is_binary(prefix) do
    rows =
      from(f in File,
        select: %{
          id: f.id,
          name: f.name,
          template_key: f.template_key,
          content_type: f.content_type,
          byte_size: f.byte_size,
          sha256: f.sha256,
          trigger_ref: f.trigger_ref,
          inserted_at: f.inserted_at,
          expires_at: f.expires_at
        },
        order_by: [desc: f.inserted_at, desc: f.id],
        limit: 100
      )
      |> Repo.all(prefix: prefix)

    {:ok, rows}
  end

  def list(_prefix), do: {:ok, []}

  @doc """
  One file of the tenant of `prefix`, WITH its bytes. `:error` when the row
  does not exist in this tenant's schema: a file of another tenant is not
  found, it is never read (INV-1, INV-5).
  """
  @spec fetch(String.t(), term()) :: {:ok, File.t()} | :error
  def fetch(prefix, id) when is_binary(prefix) do
    case Ecto.UUID.cast(id) do
      {:ok, uuid} ->
        case Repo.one(from(f in File, where: f.id == ^uuid), prefix: prefix) do
          nil -> :error
          row -> {:ok, row}
        end

      :error ->
        :error
    end
  end

  def fetch(_prefix, _id), do: :error

  @doc """
  Removes the files whose retention moment has passed. Returns the number of
  files removed. The bytes leave with the row (there is no other copy).
  """
  @spec delete_expired(String.t()) :: {:ok, non_neg_integer()}
  def delete_expired(prefix) when is_binary(prefix) do
    now = DateTime.utc_now() |> DateTime.truncate(:microsecond)

    {count, _rows} =
      Repo.delete_all(from(f in File, where: f.expires_at <= ^now), prefix: prefix)

    {:ok, count}
  end

  def delete_expired(_prefix), do: {:ok, 0}

  @doc """
  The name the SERVER generates for a file: a sanitised stem of the declared
  name plus a fresh uuid and the `.txt` extension.

  The declared name never reaches the name verbatim: every character that is
  not a letter, a digit, a dash or an underscore becomes a dash, the stem is
  cut at #{@stem_max_bytes} characters and the uuid makes two files of the same
  declared name two different files. The result therefore holds no dot, no
  slash and no `..`: it cannot be a path, whatever the caller passed in.
  """
  @spec stored_name(term()) :: String.t()
  def stored_name(declared) when is_binary(declared) do
    stem =
      declared
      |> String.downcase()
      |> String.replace(~r/[^a-z0-9_-]+/u, "-")
      |> String.replace(~r/-+/u, "-")
      |> String.trim("-")
      |> String.slice(0, @stem_max_bytes)
      |> String.trim("-")

    suffix = Ecto.UUID.generate() |> String.replace("-", "") |> String.slice(0, 12)

    if stem == "" do
      "notification-#{suffix}.txt"
    else
      "#{stem}-#{suffix}.txt"
    end
  end

  def stored_name(_declared), do: stored_name("")

  @doc """
  How many days a file is kept. The value is a SETTING of the area (a tenant
  setting later), not a rule of a process.
  """
  @spec retain_days() :: pos_integer()
  def retain_days, do: @retain_days

  @doc """
  The cap of one file, in bytes.
  """
  @spec max_file_bytes() :: pos_integer()
  def max_file_bytes, do: @max_file_bytes

  @doc """
  The cap of the declared name, in bytes. The name is checked before it is
  sanitised (SF-01: the byte bound comes first).
  """
  @spec max_declared_name_bytes() :: pos_integer()
  def max_declared_name_bytes, do: @max_declared_name_bytes

  @doc """
  The content type of a rendered notification file.
  """
  @spec content_type() :: String.t()
  def content_type, do: @content_type

  # The bytes of the file. A missing or empty payload is refused: a file with
  # no content is a mistake, not an empty file.
  defp bytes(attrs) do
    case Map.get(attrs, :bytes) do
      bytes when is_binary(bytes) and byte_size(bytes) > 0 -> {:ok, bytes}
      _other -> {:error, :file_write_failed}
    end
  end

  # The byte bound comes BEFORE the row is written: the area refuses a file it
  # cannot hold instead of storing a truncated one.
  defp size(bytes) do
    if byte_size(bytes) <= @max_file_bytes do
      :ok
    else
      {:error, :file_too_large}
    end
  end

  defp sha256(bytes) do
    :sha256
    |> :crypto.hash(bytes)
    |> Base.encode16(case: :lower)
  end
end
