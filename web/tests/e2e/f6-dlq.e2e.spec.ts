async function navigateSpa(page: import('@playwright/test').Page, targetPath: string): Promise<void> {
  await page.evaluate((nextPath) => {
    window.history.pushState({}, '', nextPath)
    window.dispatchEvent(new PopStateEvent('popstate'))
  }, targetPath)
  await page.waitForURL((url) => `${url.pathname}${url.search}` === targetPath, { timeout: 10_000 })
}

async function openDlqAndAssertRows(page: import('@playwright/test').Page, searchText?: string): Promise<void> {
  await navigateSpa(page, '/dlq')
  await expect(page.getByRole('heading', { name: 'Dead-Letter Queue' })).toBeVisible({ timeout: 10_000 })
  await expect(page.getByTestId('dlq-table')).toBeVisible()

  if (searchText) {
    const searchInput = page.getByTestId('dlq-filter-search')
    await searchInput.fill(searchText)
    await page.getByTestId('dlq-filter-apply').click()
  }

  const rows = page.locator('[data-testid^="dlq-row-"]')
  const rowCount = await rows.count()
  if (rowCount === 0) {
    await shot(page, 'DLQ-empty-state-blocker')
    throw new Error('DLQ fixture precondition failed: expected at least one DLQ row to validate DLQ-UI-01..04')
  }
}

async function firstRowActionIds(page: import('@playwright/test').Page): Promise<{ detailsButtonId: string; retryButtonId: string; discardButtonId: string }> {
  const rowTestId = await page.locator('[data-testid^="dlq-row-"]').first().getAttribute('data-testid')
  if (!rowTestId) {
    throw new Error('Missing DLQ row test id for first row')
  }

  return {
    detailsButtonId: rowTestId.replace('dlq-row-', 'dlq-details-'),
    retryButtonId: rowTestId.replace('dlq-row-', 'dlq-retry-'),
    discardButtonId: rowTestId.replace('dlq-row-', 'dlq-discard-'),
  }
}

test.describe('F6 DLQ UI (DLQ-UI-01..04)', () => {
  let adminToken = ''
  let fixtureDefinitionId = ''
  let fixtureInstanceId = ''
  let fixtureDlqId = ''

  test.beforeEach(async ({ request }) => {
    fixtureDefinitionId = ''
    fixtureInstanceId = ''
    fixtureDlqId = ''

    await assertServiceReadiness(request, API_BASE_URL)
    const creds = getAdminCredentials()
    adminToken = await getKeycloakToken(request, creds.username, creds.password)
    const fixture = await ensureActionableDlqFixture(request, adminToken)
    fixtureDefinitionId = fixture.definitionId
    fixtureInstanceId = fixture.instanceId
    fixtureDlqId = fixture.dlqId
  })

  test.afterEach(async ({ request }) => {
    if (!adminToken) return

    const cleanupErrors: string[] = []

    if (fixtureDlqId) {
      try {
        await discardDlqFixture(request, adminToken, fixtureDlqId)
      } catch (error) {
        cleanupErrors.push(`discard dlq ${fixtureDlqId}: ${String(error)}`)
      }
    }

    if (fixtureInstanceId) {
      try {
        await cancelFixtureInstance(request, adminToken, fixtureInstanceId)
      } catch (error) {
        cleanupErrors.push(`cancel instance ${fixtureInstanceId}: ${String(error)}`)
      }
    }

    if (fixtureDefinitionId) {
      try {
        await deleteFixtureDefinition(request, adminToken, fixtureDefinitionId)
      } catch (error) {
        cleanupErrors.push(`delete definition ${fixtureDefinitionId}: ${String(error)}`)
      }
    }

    fixtureDefinitionId = ''
    fixtureInstanceId = ''
    fixtureDlqId = ''

    if (cleanupErrors.length > 0) {
      throw new Error(`F6 fixture cleanup failed (${cleanupErrors.join(' | ')})`)
    }
  })

  test('TC-DLQ-UI-01-E2E-01: DLQ list renders required columns and rows', async ({ page }) => {
    await loginWithToken(page, adminToken)
    await openDlqAndAssertRows(page, fixtureDlqId)

    await expect(page.getByRole('columnheader', { name: 'Source' })).toBeVisible()
    await expect(page.getByRole('columnheader', { name: 'Instance' })).toBeVisible()
    await expect(page.getByRole('columnheader', { name: 'Reason' })).toBeVisible()
    await expect(page.getByRole('columnheader', { name: 'Retry count' })).toBeVisible()
    await expect(page.getByRole('columnheader', { name: 'Created' })).toBeVisible()
    await expect(page.getByRole('columnheader', { name: 'Status' })).toBeVisible()
    await shot(page, 'DLQ-UI-01-list')
  })

  test('TC-DLQ-UI-02-E2E-01: DLQ detail panel shows failure reason, retry history, and payload context', async ({ page }) => {
    await loginWithToken(page, adminToken)
    await openDlqAndAssertRows(page, fixtureDlqId)

    const { detailsButtonId } = await firstRowActionIds(page)
    await page.getByTestId(detailsButtonId).click()
    await expect(page.getByTestId('dlq-detail-panel')).toBeVisible()
    await expect(page.getByText('Full failure reason')).toBeVisible()
    await expect(page.getByText('Retry history')).toBeVisible()
    await expect(page.getByText('Context JSON')).toBeVisible()
    await expect(page.getByText('Source payload')).toBeVisible()
    await shot(page, 'DLQ-UI-02-detail-panel')
  })

  test('TC-DLQ-UI-03-E2E-01: Retry action attempts POST /dlq/:id/retry and shows retrying or error feedback', async ({ page }) => {
    await loginWithToken(page, adminToken)
    await openDlqAndAssertRows(page, fixtureDlqId)

    const { retryButtonId } = await firstRowActionIds(page)
    await expect(page.getByTestId(retryButtonId)).toBeVisible({ timeout: 10_000 })
    await page.getByTestId(retryButtonId).click()

    const retryIndicator = page.locator('[data-testid^="dlq-row-"]').first().getByText(/retrying/i)
    const actionError = page.getByText('Retry failed. Please try again.')

    await Promise.race([
      retryIndicator.waitFor({ state: 'visible', timeout: 10_000 }),
      actionError.waitFor({ state: 'visible', timeout: 10_000 }),
    ])
    await shot(page, 'DLQ-UI-03-retry-attempt')
  })

  test('TC-DLQ-UI-04-E2E-01: Discard action opens confirmation dialog with cancellation warning context', async ({ page }) => {
    await loginWithToken(page, adminToken)
    await openDlqAndAssertRows(page, fixtureDlqId)

    const { discardButtonId } = await firstRowActionIds(page)
    await expect(page.getByTestId(discardButtonId)).toBeVisible({ timeout: 10_000 })
    await page.getByTestId(discardButtonId).click()

    await expect(page.getByTestId('dlq-discard-dialog')).toBeVisible()
    await expect(page.getByText('Discard this DLQ item?')).toBeVisible()
    await expect(page.getByText('Discarding may cancel the associated instance.')).toBeVisible()
    await shot(page, 'DLQ-UI-04-discard-confirmation')
    await page.getByRole('button', { name: 'Cancel' }).click()
    await expect(page.getByTestId('dlq-discard-dialog')).toBeHidden()
  })
})
