import { expect, test } from '@playwright/test'
import { randomUUID } from 'crypto'
import * as fs from 'fs'
import * as path from 'path'
import { getKeycloakToken, loginWithToken, assertServiceReadiness } from './helpers'

const SCREENSHOTS_DIR = 'tests/screenshots'
const API_BASE_URL = process.env.BPM_TEST_URL ?? 'http://127.0.0.1:4000'
const API_PREFIX = '/api/v1'

function getEnvOrDefault(name: string, fallback: string): string {
  const value = process.env[name]
  return value && value.trim() ? value : fallback
}

function getAdminCredentials(): { username: string; password: string } {
  return {
    username: getEnvOrDefault('BPM_E2E_ADMIN_USERNAME', 'admin-user'),
    password: getEnvOrDefault('BPM_E2E_ADMIN_PASSWORD', 'admin-pass'),
  }
}

function shotPath(name: string): string {
  const dir = path.resolve(SCREENSHOTS_DIR)
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true })
  return path.join(dir, `F6-${name}.png`)
}

async function shot(page: import('@playwright/test').Page, name: string): Promise<void> {
  await page.screenshot({ path: shotPath(name), fullPage: true })
}

function decodeJwtPayload(token: string): { sub?: string; preferred_username?: string; [key: string]: unknown } {
  const parts = token.split('.')
  if (parts.length !== 3) throw new Error('Invalid JWT token')
  return JSON.parse(Buffer.from(parts[1], 'base64').toString('utf-8')) as { sub?: string; preferred_username?: string; [key: string]: unknown }
}

async function createDlqFixtureDefinition(
  request: import('@playwright/test').APIRequestContext,
  token: string,
  assigneeUserId: string,
  fixtureId: string,
): Promise<string> {
  const createResponse = await request.post(`${API_BASE_URL}${API_PREFIX}/definitions`, {
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    data: {
      name: `F6 DLQ Fixture ${fixtureId}`,
      version: '1.0.0',
      description: 'F6 DLQ UI fixture definition generated by E2E setup',
      stage: null,
      graph: {
        nodes: [
          { id: 'start', node_type: 'START', label: 'Start', attributes: null },
          {
            id: 'task-1',
            node_type: 'HUMAN_TASK',
            label: 'Approve payload',
            attributes: JSON.stringify({
              role: 'reviewer',
              assignee_type: 'USER',
              assignee_ref: assigneeUserId,
              form_schema: {
                type: 'object',
                properties: {
                  approved: { type: 'boolean', title: 'Approved' },
                  comment: { type: 'string', title: 'Comment' },
                },
                required: ['approved', 'comment'],
              },
            }),
          },
          {
            id: 'service-1',
            node_type: 'SERVICE_TASK',
            label: 'Failing webhook simulation',
            attributes: JSON.stringify({
              endpoint: 'http://127.0.0.1:65535/fail-fast',
              method: 'POST',
              timeout_ms: 150,
              retry_limit: 0,
            }),
          },
          { id: 'end', node_type: 'END', label: 'End', attributes: null },
        ],
        edges: [
          { id: 'e1', source: 'start', target: 'task-1', condition: null, is_default: false },
          { id: 'e2', source: 'task-1', target: 'service-1', condition: null, is_default: false },
          { id: 'e3', source: 'service-1', target: 'end', condition: null, is_default: false },
        ],
      },
    },
  })

  if (!createResponse.ok()) {
    const body = await createResponse.text()
    throw new Error(`F6 fixture definition create failed (${createResponse.status()}): ${body}`)
  }

  const created = (await createResponse.json()) as { id?: string }
  if (!created.id) throw new Error('F6 fixture definition create response missing id')

  const activateResponse = await request.post(`${API_BASE_URL}${API_PREFIX}/definitions/${created.id}/activate`, {
    headers: {
      Authorization: `Bearer ${token}`,
    },
  })
  if (!activateResponse.ok()) {
    const body = await activateResponse.text()
    throw new Error(`F6 fixture definition activate failed (${activateResponse.status()}): ${body}`)
  }

  return created.id
}

async function startFixtureInstance(
  request: import('@playwright/test').APIRequestContext,
  token: string,
  definitionId: string,
  fixtureId: string,
): Promise<string> {
  const response = await request.post(`${API_BASE_URL}${API_PREFIX}/instances`, {
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    data: {
      definition_id: definitionId,
      correlation_key: `f6-dlq-${fixtureId}`,
      initial_variables: {
        source: 'f6-dlq-e2e',
        fixture_id: fixtureId,
      },
    },
  })

  if (!response.ok()) {
    const body = await response.text()
    throw new Error(`F6 fixture instance start failed (${response.status()}): ${body}`)
  }

  const payload = (await response.json()) as { instance_id?: string }
  if (!payload.instance_id) throw new Error('F6 fixture start response missing instance_id')
  return payload.instance_id
}

async function waitForTaskId(
  request: import('@playwright/test').APIRequestContext,
  token: string,
  instanceId: string,
): Promise<string> {
  const deadline = Date.now() + 20_000
  while (Date.now() < deadline) {
    const response = await request.get(`${API_BASE_URL}${API_PREFIX}/tasks`, {
      headers: {
        Authorization: `Bearer ${token}`,
      },
      params: {
        instance_id: instanceId,
      },
    })

    if (response.ok()) {
      const payload = (await response.json()) as { items?: Array<{ id?: string }> }
      const taskId = payload.items?.[0]?.id
      if (taskId) return taskId
    }

    await new Promise((resolve) => setTimeout(resolve, 500))
  }

  throw new Error(`F6 fixture task did not appear for instance ${instanceId}`)
}

async function completeFixtureTask(
  request: import('@playwright/test').APIRequestContext,
  token: string,
  taskId: string,
): Promise<void> {
  const response = await request.post(`${API_BASE_URL}${API_PREFIX}/tasks/${taskId}/complete`, {
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    data: {
      output_variables: {
        approved: true,
        comment: 'trigger service task failure for dlq fixture',
      },
    },
  })

  if (!response.ok()) {
    const body = await response.text()
    throw new Error(`F6 fixture task completion failed (${response.status()}): ${body}`)
  }
}

async function fetchDlqItems(
  request: import('@playwright/test').APIRequestContext,
  token: string,
): Promise<Array<{ id: string; instance_id?: string | null }>> {
  const response = await request.get(`${API_BASE_URL}/dlq`, {
    headers: {
      Authorization: `Bearer ${token}`,
    },
    params: {
      page_size: '50',
    },
  })

  if (!response.ok()) {
    const body = await response.text()
    throw new Error(`F6 fixture failed to list DLQ items (${response.status()}): ${body}`)
  }

  const payload = (await response.json()) as { items?: Array<{ id?: string; instance_id?: string | null }> }
  const items = Array.isArray(payload.items) ? payload.items : []
  return items
    .filter((item): item is { id: string; instance_id?: string | null } => typeof item.id === 'string' && item.id.length > 0)
}

async function waitForNewDlqItem(
  request: import('@playwright/test').APIRequestContext,
  token: string,
  previousIds: Set<string>,
  fixtureInstanceId: string,
): Promise<{ id: string; instance_id?: string | null }> {
  const deadline = Date.now() + 20_000
  while (Date.now() < deadline) {
    const items = await fetchDlqItems(request, token)
    for (const item of items) {
      if (previousIds.has(item.id)) continue
      if (item.instance_id !== fixtureInstanceId) continue
      return item
    }

    await new Promise((resolve) => setTimeout(resolve, 500))
  }

  throw new Error('F6 fixture did not produce a new actionable DLQ item with instance context')
}

async function ensureActionableDlqFixture(
  request: import('@playwright/test').APIRequestContext,
  token: string,
): Promise<{ fixtureId: string; definitionId: string; instanceId: string; dlqId: string }> {
  const jwt = decodeJwtPayload(token)
  const assigneeUserId = typeof jwt.sub === 'string' && jwt.sub.length > 0 ? jwt.sub : 'admin-user'
  const baselineItems = await fetchDlqItems(request, token)
  const baselineIds = new Set(baselineItems.map((item) => item.id))
  const fixtureId = randomUUID()

  const definitionId = await createDlqFixtureDefinition(request, token, assigneeUserId, fixtureId)
  const instanceId = await startFixtureInstance(request, token, definitionId, fixtureId)
  const taskId = await waitForTaskId(request, token, instanceId)
  await completeFixtureTask(request, token, taskId)
  const dlqItem = await waitForNewDlqItem(request, token, baselineIds, instanceId)

  return { fixtureId, definitionId, instanceId, dlqId: dlqItem.id }
}

async function discardDlqFixture(
  request: import('@playwright/test').APIRequestContext,
  token: string,
  dlqId: string,
): Promise<void> {
  const response = await request.post(`${API_BASE_URL}/dlq/${dlqId}/discard`, {
    headers: {
      Authorization: `Bearer ${token}`,
    },
  })

  if (![200, 202, 204, 404].includes(response.status())) {
    const body = await response.text()
    throw new Error(`F6 fixture DLQ discard failed for ${dlqId} (${response.status()}): ${body}`)
  }
}

