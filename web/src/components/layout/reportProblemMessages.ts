export type ReportProblemMessages = Record<string, string>

export function useReportProblemMessages(): ReportProblemMessages {
  return reportProblemMessages[useUiLocale()]
}

/** Replaces {name} placeholders in a catalog text. */
export function fill(text: string, values: Record<string, string | number>): string {
  return Object.entries(values).reduce((acc, [k, v]) => acc.split(`{${k}}`).join(String(v)), text)
}
