defmodule Letflow.Entities.ManagedTypesCallersTest do
  @moduledoc """
  REQ-496 / GH #2530 (design `lib/letflow/design/req496-managed-by-and-scope-node-paths.md` §3.5,
  §9 T-34; spec `test/specs/REQ-496.md`), extended by GH #2583 (design
  `lib/letflow/design/gh2583-records-managed-type-guard.md` Revisions 1-2, section 7, tests
  T-17..T-20 and T-22..T-28; spec `test/specs/GH-2583.md`).

  "The owner is identified by caller, never by request data" rests on WHO can originate a
  `Letflow.Entities.ManagedTypes.Owner` and WHO can hand one to `Letflow.Entities.Records`.
  `mix letflow.check_boundaries` cannot express per-function caller allow-lists, so this test
  pins them over the AST (not grep: a comment or doc naming a function is not a call) of every
  `lib/**/*.ex` and `test/support/**/*.ex` file (design 7.1; `test/**/*.exs` is excluded because
  test bodies forge `Owner` values on purpose). Every rule runs on the pipe-normalised AST
  (`a |> f(b)` is seen as `f(a, b)`):

    * R1 (load-bearing): `Records.create_record/update_record/delete_record/command_multi` with a
      third argument other than the literal `:tenant` (direct, piped, a `/3` capture,
      `Function.capture/3`, or `apply/3` / `Kernel.apply/3` / `:erlang.apply/3` with a literal
      Records module and function) only in `@authority_callers`. Only QUALIFIED receivers
      (`Records`, `Entities.Records`, `Letflow.Entities.Records`, or the atom) count: local calls
      cannot reach `Records` because R1b forbids importing it.
    * R1b: no `import` and no `alias ..., as:` of `Letflow.Entities.Records`,
      `Letflow.Entities.Definitions` or `Letflow.Entities.ManagedTypes` outside their definers,
      except exactly `import ManagedTypes, only: [is_authority: 1]` (short or fully qualified) in
      `lib/letflow/entities/records.ex`. A plain multi-alias without `as:` is allowed.
    * R2: every call NAMED `owner_for!` (any receiver, local included) outside `managed_types.ex`
      has one argument: `__MODULE__` inside a `defmanifest` module, or an alias resolving to a
      `defmanifest` module whose file sits directly in `lib/letflow/modules/<id>` or
      `test/support/modules/<id>`, called from a file under that directory (whole path segments).
      Anything else (unknown alias, variable, atom literal, capture, apply) is a violation.
    * R3: calls NAMED `module_owner` (plus captures and applies of it) only in `managed_types.ex`
      and `installs.ex`.
    * R4: the `Owner` struct is built (`%Owner{}`, `struct/struct!`, a `%{__struct__: Owner}` map
      literal, `Map.put/put_new/replace/replace!` of `:__struct__`) only in `managed_types.ex`.
    * R5: qualified `Definitions.create_definition/3` with a non-`:tenant` owner only in
      `solution_pack.ex` threading `owner`; `SolutionPack.install/4` with a non-`:tenant` owner
      only in `installs.ex`.
    * R6 (GH #2596): under `lib/letflow/modules/exam/`, no qualified `Records.create_record |
      update_record | delete_record` call has two arguments or a literal `:tenant` third argument
      (the exam module writes only its managed runtime types; the spec is `test/specs/GH2596-exam-managed.md`).
      The exam writers `session.ex`, `certificate.ex`, `anti_cheat.ex`, `authoring.ex` are in `@authority_callers`
      and call `owner_for!(Exam)` (R2 directory rule).

  Accepted limits (design 7.5), NOT covered: computed module or function names
  (`apply(mod_var, fun_var, args)`, `Module.concat/1`, `String.to_atom/1`),
  `:erlang.binary_to_term/1`, `Code.eval_*` / `Code.compile_*`, code generated by macros defined
  away from the call site, `.exs` files and dependencies.

  Every rule is a pure function over `[{path, ast}]`; T-22..T-28 feed synthetic snippets through
  the SAME functions the real-tree tests (T-17..T-20) use. Pure file reads, so `async: true`.
  """

  use ExUnit.Case, async: true

  @managed_types "lib/letflow/entities/managed_types.ex"
  @installs "lib/letflow/modules/installs.ex"
  @solution_pack "lib/letflow/definitions/solution_pack.ex"
  @definitions "lib/letflow/entities/definitions.ex"
  @records "lib/letflow/entities/records.ex"
  @handler_writes "lib/letflow/entities/handler_writes.ex"
  @fixture_managed "test/support/modules/fixture_managed/fixture_managed.ex"
  @script_policy_fixture "test/support/script_policy_fixture.ex"
  # GH #2596: the exam module's own record writers; each passes the exam Owner (`exam_owner/0`).
  @exam_anti_cheat "lib/letflow/modules/exam/anti_cheat.ex"
  @exam_authoring "lib/letflow/modules/exam/authoring.ex"
  @exam_certificate "lib/letflow/modules/exam/certificate.ex"
  @exam_session "lib/letflow/modules/exam/session.ex"
  # GH #2682 PR b: the exam snapshot module writes the late snapshot / certificate facts through
  # the exam Owner (Records /3), like the other exam writers.
  @exam_snapshot "lib/letflow/modules/exam/snapshot.ex"
  @exam_writers [
    @exam_anti_cheat,
    @exam_authoring,
    @exam_certificate,
    @exam_session,
    @exam_snapshot
  ]
  @exam_dir ["lib", "letflow", "modules", "exam"]

  # Static allow-list for R1: adding a file here is a reviewed diff (design 7.3). Kept in the
  # sorted order `r1_files/1` returns (the scan set is path-sorted).
  @authority_callers [@handler_writes] ++ @exam_writers ++ [@fixture_managed]
  # R3 / R4 allow-lists (unchanged from REQ-496 T-34).
  @module_owner_callers [@managed_types, @installs]
  @owner_builders [@managed_types]

  @write_funs [:create_record, :update_record, :delete_record, :command_multi]
  @apply_receivers [nil, [:Kernel], [:erlang]]
  @def_kinds [:def, :defp, :defmacro, :defmacrop, :defguard, :defguardp]
  @records_receivers [[:Records], [:Entities, :Records], [:Letflow, :Entities, :Records]]
  @definitions_receivers [
    [:Definitions],
    [:Entities, :Definitions],
    [:Letflow, :Entities, :Definitions]
  ]
  @banned_definers %{
    Records: @records,
    Definitions: @definitions,
    ManagedTypes: @managed_types
  }
  @allowed_records_import_opts [[only: [is_authority: 1]]]
  @owner_atom :"Elixir.Letflow.Entities.ManagedTypes.Owner"
  @fake "lib/letflow/fake.ex"

  setup_all do
    {:ok, files: parsed()}
  end

  # ── scan set ────────────────────────────────────────────────────────────────────────────────

  defp scanned_files do
    (Path.wildcard("lib/**/*.ex") ++ Path.wildcard("test/support/**/*.ex")) |> Enum.sort()
  end

  defp parsed do
    for path <- scanned_files() do
      {path, path |> File.read!() |> Code.string_to_quoted!(file: path)}
    end
  end

  defp synthetic(sources) do
    for {path, source} <- sources, do: {path, Code.string_to_quoted!(source, file: path)}
  end

  # ── AST helpers (design 7.2) ────────────────────────────────────────────────────────────────

  # Every `lhs |> f(args)` becomes `f(lhs, args)`; nested pipes flatten innermost first.
  defp normalize_pipes(ast) do
    Macro.postwalk(ast, fn
      {:|>, _, [lhs, {fun, meta, args}]} when is_list(args) -> {fun, meta, [lhs | args]}
      node -> node
    end)
  end

  # Every call node as {name, receiver, args}: receiver is the alias segments of an alias
  # receiver, the split name of an atom receiver (`[:erlang]` for an Erlang module), the marker
  # `[:__dynamic__]` for a computed receiver, or nil for a local call.
  defp calls(ast) do
    {_ast, acc} =
      Macro.prewalk(ast, [], fn
        {{:., _, [receiver, name]}, _, args} = node, acc when is_atom(name) and is_list(args) ->
          {node, [{name, receiver_segments(receiver), args} | acc]}

        {name, _, args} = node, acc when is_atom(name) and is_list(args) ->
          {node, [{name, nil, args} | acc]}

        node, acc ->
          {node, acc}
      end)

    Enum.reverse(acc)
  end

  # Every `&name/arity` and `&Receiver.name/arity` capture as {name, receiver, arity}.
  defp captures(ast) do
    {_ast, acc} =
      Macro.prewalk(ast, [], fn
        {:&, _, [{:/, _, [{{:., _, [receiver, name]}, _, []}, arity]}]} = node, acc
        when is_atom(name) ->
          {node, [{name, receiver_segments(receiver), arity} | acc]}

        {:&, _, [{:/, _, [{name, _, context}, arity]}]} = node, acc
        when is_atom(name) and is_atom(context) ->
          {node, [{name, nil, arity} | acc]}

        node, acc ->
          {node, acc}
      end)

    Enum.reverse(acc)
  end

  defp receiver_segments({:__aliases__, _, segments}), do: segments
  defp receiver_segments(atom) when is_atom(atom), do: atom_segments(atom)
  defp receiver_segments(_computed), do: [:__dynamic__]

  defp atom_segments(atom) do
    case Atom.to_string(atom) do
      "Elixir." <> rest -> rest |> String.split(".") |> Enum.map(&String.to_atom/1)
      _erlang -> [atom]
    end
  end

  # A literal module reference (alias or atom) as segments; nil for anything computed.
  defp literal_module({:__aliases__, _, segments}), do: segments

  defp literal_module(atom) when is_atom(atom) and atom not in [nil, true, false],
    do: atom_segments(atom)

  defp literal_module(_other), do: nil

  defp qualified?(nil, _target), do: false
  defp qualified?(receiver, :records), do: receiver in @records_receivers
  defp qualified?(receiver, :definitions), do: receiver in @definitions_receivers

  defp records_module?(node), do: qualified?(literal_module(node), :records)

  # Replaces every def/defp/defmacro/... head with nothing (the body is kept), so a function
  # DEFINITION named like a call is not counted where that matters (the defmanifest check).
  defp strip_def_heads(ast) do
    Macro.prewalk(ast, fn
      {kind, meta, [_head | rest]} when kind in @def_kinds and is_list(rest) -> {kind, meta, rest}
      node -> node
    end)
  end

  # [{module_segments | nil, body}] for every defmodule (nested modules split out and named
  # Parent.Child), plus {nil, rest} for code outside any defmodule.
  defp module_bodies(ast) do
    {rest, modules} = split_modules(ast, nil)
    [{nil, rest} | modules]
  end

  defp split_modules(ast, parent) do
    Macro.prewalk(ast, [], fn
      {:defmodule, _, [name_node, [{:do, body}]]}, acc ->
        segments = nested_name(literal_module(name_node), parent)
        {inner_rest, inner_modules} = split_modules(body, segments)
        {:__nested_module__, [{segments, inner_rest} | inner_modules] ++ acc}

      node, acc ->
        {node, acc}
    end)
  end

  defp nested_name(nil, _parent), do: [:__dynamic__]
  defp nested_name(segments, nil), do: segments
  defp nested_name(segments, parent), do: parent ++ segments

  defp defmanifest?(body) do
    body
    |> strip_def_heads()
    |> calls()
    |> Enum.any?(fn
      {:defmanifest, nil, _args} -> true
      {:defmanifest, [:Letflow, :Modules, :Module], _args} -> true
      _other -> false
    end)
  end

  # Module segments => defining path, for every module that calls defmanifest.
  defp manifest_modules(files) do
    for {path, ast} <- files,
        {segments, body} <- module_bodies(ast),
        segments != nil,
        defmanifest?(body),
        into: %{},
        do: {segments, path}
  end

  # Short name => full segments, from every `alias` directive in the file.
  defp alias_map(ast) do
    {_ast, acc} =
      Macro.prewalk(ast, %{}, fn
        {:alias, _, [{:__aliases__, _, segments} | opts]} = node, acc ->
          {node, put_alias(acc, segments, alias_as(opts))}

        {:alias, _, [{{:., _, [{:__aliases__, _, base}, :{}]}, _, children}]} = node, acc ->
          acc =
            Enum.reduce(children, acc, fn
              {:__aliases__, _, segments}, inner -> put_alias(inner, base ++ segments, nil)
              _other, inner -> inner
            end)

          {node, acc}

        node, acc ->
          {node, acc}
      end)

    acc
  end

  defp alias_as([opts]) when is_list(opts) do
    case Keyword.get(opts, :as) do
      {:__aliases__, _, [short]} -> short
      _none -> nil
    end
  end

  defp alias_as(_opts), do: nil

  defp put_alias(acc, segments, as) do
    if Enum.all?(segments, &is_atom/1),
      do: Map.put(acc, as || List.last(segments), segments),
      else: acc
  end

  defp expand_alias([first | rest] = segments, aliases) do
    case Map.fetch(aliases, first) do
      {:ok, full} -> full ++ rest
      :error -> segments
    end
  end

  defp entry_dir?(["lib", "letflow", "modules", _id]), do: true
  defp entry_dir?(["test", "support", "modules", _id]), do: true
  defp entry_dir?(_other), do: false

  # Whole path segments, never a string prefix (design 7.3 R2, Revision 2).
  defp under_dir?(path, dir_segments) do
    path_segments = Path.split(path)

    length(path_segments) > length(dir_segments) and
      Enum.take(path_segments, length(dir_segments)) == dir_segments
  end

  # ── rules (pure functions over [{path, ast}]) ───────────────────────────────────────────────

  # R1: [{path, site}] for every Records write call that can carry a non-:tenant authority.
  defp r1_violations(files) do
    for {path, ast} <- files, path != @records, site <- r1_sites(ast), do: {path, site}
  end

  defp r1_sites(ast) do
    normalised = normalize_pipes(ast)
    all_calls = calls(normalised)

    direct =
      for {fun, receiver, [_attrs, _prefix, authority]} <- all_calls,
          fun in @write_funs,
          qualified?(receiver, :records),
          authority != :tenant,
          do: {:call, fun}

    captured =
      for {fun, receiver, 3} <- captures(normalised),
          fun in @write_funs,
          qualified?(receiver, :records),
          do: {:capture, fun}

    function_captured =
      for {:capture, [:Function], [module, fun, arity]} <- all_calls,
          fun in @write_funs,
          records_module?(module),
          arity == 3 or not is_integer(arity),
          do: {:function_capture, fun}

    applied =
      for {:apply, receiver, [module, fun, args]} <- all_calls,
          receiver in @apply_receivers,
          fun in @write_funs,
          records_module?(module),
          not tenant_args?(args),
          do: {:apply, fun}

    direct ++ captured ++ function_captured ++ applied
  end

  defp tenant_args?([_attrs, _prefix]), do: true
  defp tenant_args?([_attrs, _prefix, :tenant]), do: true
  defp tenant_args?(_other), do: false

  defp r1_files(files), do: files |> r1_violations() |> Enum.map(&elem(&1, 0)) |> Enum.uniq()

  # R1b: [{path, kind, target}] for every banned import / `alias ..., as:`.
  defp r1b_violations(files) do
    for {path, ast} <- files,
        {kind, target, opts} <- directives(ast),
        banned_directive?(path, kind, target, opts),
        do: {path, kind, target}
  end

  defp directives(ast) do
    {_ast, acc} =
      Macro.prewalk(ast, [], fn
        {:import, _, [module | opts]} = node, acc ->
          {node, [{:import, banned_target(module), opts} | acc]}

        {:alias, _, [module, opts]} = node, acc when is_list(opts) ->
          {node, [{:alias, banned_target(module), opts} | acc]}

        node, acc ->
          {node, acc}
      end)

    for {_kind, target, _opts} = directive <- Enum.reverse(acc), target != nil, do: directive
  end

  defp banned_target(node) do
    case literal_module(node) do
      [:Letflow, :Entities, name] -> banned_name(name)
      [:Entities, name] -> banned_name(name)
      [name] -> banned_name(name)
      _other -> nil
    end
  end

  defp banned_name(name) when name in [:Records, :Definitions, :ManagedTypes], do: name
  defp banned_name(_name), do: nil

  defp banned_directive?(path, kind, target, opts) do
    cond do
      path == Map.fetch!(@banned_definers, target) -> false
      kind == :import -> not allowed_records_import?(path, target, opts)
      kind == :alias -> Keyword.keyword?(opts) and Keyword.has_key?(opts, :as)
    end
  end

  defp allowed_records_import?(path, target, opts),
    do: path == @records and target == :ManagedTypes and opts == @allowed_records_import_opts

  # R2: [{path, reason}] for every owner_for! site outside managed_types.ex that is not allowed.
  defp r2_violations(files) do
    index = manifest_modules(files)

    for {path, ast} <- files,
        path != @managed_types,
        reason <- r2_file(path, ast, index),
        do: {path, reason}
  end

  defp r2_file(path, ast, index) do
    aliases = alias_map(ast)

    for {module, body} <- module_bodies(ast),
        site <- owner_fun_sites(normalize_pipes(body), :owner_for!),
        reason <- [r2_reason(site, module, body, path, aliases, index)],
        reason != :ok,
        do: reason
  end

  defp r2_reason({:call, [{:__MODULE__, _, context}]}, module, body, _path, _aliases, _index)
       when is_atom(context) do
    if module != nil and defmanifest?(body), do: :ok, else: {:module_without_defmanifest, module}
  end

  defp r2_reason({:call, [{:__aliases__, _, segments}]}, _module, _body, path, aliases, index) do
    full = expand_alias(segments, aliases)

    case Map.fetch(index, full) do
      :error ->
        {:unresolved_entry_module, full}

      {:ok, defining_path} ->
        dir = defining_path |> Path.dirname() |> Path.split()

        if entry_dir?(dir) and under_dir?(path, dir),
          do: :ok,
          else: {:outside_entry_directory, full}
    end
  end

  defp r2_reason({:call, args}, _module, _body, _path, _aliases, _index),
    do: {:unresolvable_argument, Macro.to_string(args)}

  defp r2_reason({kind, _detail}, _module, _body, _path, _aliases, _index),
    do: {kind, :owner_for!}

  # Sites of a function NAMED `name`, any receiver: calls, captures, Function.capture, apply.
  defp owner_fun_sites(normalised, name) do
    all_calls = calls(normalised)

    direct = for {^name, _receiver, args} <- all_calls, do: {:call, args}
    captured = for {^name, _receiver, _arity} <- captures(normalised), do: {:capture, name}

    function_captured =
      for {:capture, [:Function], [_module, ^name, _arity]} <- all_calls,
          do: {:function_capture, name}

    applied =
      for {:apply, receiver, [_module, ^name, _args]} <- all_calls,
          receiver in @apply_receivers,
          do: {:apply, name}

    direct ++ captured ++ function_captured ++ applied
  end

  defp owner_for_callers(files) do
    for {path, ast} <- files,
        path != @managed_types,
        owner_fun_sites(normalize_pipes(ast), :owner_for!) != [],
        do: path
  end

  # R6 (GH #2596, design 5.5): [{path, site}] for every qualified Records create/update/delete
  # call under lib/letflow/modules/exam/ that carries NO authority: two arguments, or a literal
  # `:tenant` third argument. The exam module writes only managed runtime types, so a tenant
  # write would be refused at runtime; this pins it statically.
  defp r6_violations(files) do
    for {path, ast} <- files,
        under_dir?(path, @exam_dir),
        {fun, receiver, args} <- calls(normalize_pipes(ast)),
        fun in [:create_record, :update_record, :delete_record],
        qualified?(receiver, :records),
        tenant_authority?(args),
        do: {path, fun}
  end

  defp tenant_authority?([_attrs, _prefix]), do: true
  defp tenant_authority?([_attrs, _prefix, :tenant]), do: true
  defp tenant_authority?(_other), do: false

  # R3: every file with a module_owner site (call, capture, Function.capture, apply).
  defp module_owner_callers(files) do
    for {path, ast} <- files,
        owner_fun_sites(normalize_pipes(ast), :module_owner) != [],
        do: path
  end

  defp r3_violations(files), do: module_owner_callers(files) -- @module_owner_callers

  # R4: files that build an Owner struct.
  defp owner_builders(files), do: for({path, ast} <- files, builds_owner?(ast), do: path)

  defp owner_ref?({:__aliases__, _, segments}), do: List.last(segments) == :Owner
  defp owner_ref?(@owner_atom), do: true
  defp owner_ref?(_other), do: false

  defp struct_key_owner?(pairs) when is_list(pairs) do
    Enum.any?(pairs, fn
      {:__struct__, value} -> owner_ref?(value)
      {:|, _, [_map, inner]} -> struct_key_owner?(inner)
      _other -> false
    end)
  end

  defp struct_key_owner?(_other), do: false

  defp builds_owner?(ast) do
    normalised = normalize_pipes(ast)

    {_ast, found?} =
      Macro.prewalk(normalised, false, fn
        {:%, _, [struct_alias, _fields]} = node, acc ->
          {node, acc or owner_ref?(struct_alias)}

        {:%{}, _, pairs} = node, acc ->
          {node, acc or struct_key_owner?(pairs)}

        {fun, _, [struct_alias | _]} = node, acc when fun in [:struct, :struct!] ->
          {node, acc or owner_ref?(struct_alias)}

        {{:., _, [{:__aliases__, _, [:Kernel]}, fun]}, _, [struct_alias | _]} = node, acc
        when fun in [:struct, :struct!] ->
          {node, acc or owner_ref?(struct_alias)}

        node, acc ->
          {node, acc}
      end)

    found? or
      Enum.any?(calls(normalised), fn
        {fun, [:Map], [_map, :__struct__, value]}
        when fun in [:put, :put_new, :replace, :replace!] ->
          owner_ref?(value)

        _other ->
          false
      end)
  end

  # R5: qualified create_definition/3 with a non-:tenant owner, as {path, owner_source}.
  # definitions.ex is excluded: it DEFINES create_definition/3 (its only call is the local
  # /2 -> :tenant delegate, which the qualified filter already ignores).
  defp r5_create_definition_sites(files) do
    for {path, ast} <- files,
        path != @definitions,
        {:create_definition, receiver, [_attrs, _prefix, owner]} <- calls(normalize_pipes(ast)),
        qualified?(receiver, :definitions),
        owner != :tenant,
        uniq: true,
        do: {path, Macro.to_string(owner)}
  end

  defp r5_install_callers(files) do
    for {path, ast} <- files,
        {:install, receiver, [_doc, _actor, _opts, owner]} <- calls(normalize_pipes(ast)),
        receiver != nil and List.last(receiver) == :SolutionPack,
        owner != :tenant,
        uniq: true,
        do: path
  end

  # ── T-20 vacuity + R3/R4/R5 on the real tree (existing REQ-496 T-34 intent kept) ────────────

  describe "T-20 (AC2): the scan set and the existing rules on the widened, pipe-normalised scan" do
    test "lib/ and test/support/ have files to scan (the scan cannot pass vacuously)", %{
      files: files
    } do
      paths = Enum.map(files, &elem(&1, 0))
      assert @managed_types in paths
      assert @installs in paths
      assert @records in paths
      assert @fixture_managed in paths
      assert @script_policy_fixture in paths
      assert length(paths) > 100
    end

    test "module_owner is called only in installs.ex (defined in managed_types.ex)", %{
      files: files
    } do
      assert Enum.sort(module_owner_callers(files)) == Enum.sort(@module_owner_callers)
      assert r3_violations(files) == []
    end

    test "the Owner struct is built (literal, struct/2, __struct__ map or Map.put) only in managed_types.ex",
         %{files: files} do
      assert owner_builders(files) == @owner_builders
    end

    test "create_definition/3 with a non-:tenant owner only in solution_pack.ex, threading install/4's owner",
         %{files: files} do
