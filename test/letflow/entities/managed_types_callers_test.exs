    end

    test "an own-directory writer naming its entry module (full or aliased) is allowed" do
      writer = "test/support/modules/fixture_managed/writer.ex"
      deep = "test/support/modules/fixture_managed/sub/deeper.ex"

      assert r2_with_manifest(writer, """
             defmodule W do
               def o, do: ManagedTypes.owner_for!(Letflow.Modules.FixtureManaged)
             end
             """) == []

      assert r2_with_manifest(deep, """
             defmodule W do
               alias Letflow.Modules.FixtureManaged
